const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('host', {
  his: e => ipcRenderer.send('his', e),
  mode: m => ipcRenderer.send('mode', m),
  drop: title => ipcRenderer.send('drop', title),
  clear: () => ipcRenderer.send('clear'),
  undo: () => ipcRenderer.send('undo'),
  removed: id => ipcRenderer.send('removed', id),
  send: () => ipcRenderer.send('send'),
  noteAt: (x, y) => ipcRenderer.send('note-at', x, y),
  noteDone: text => ipcRenderer.send('note-done', text),
  steer: (id, at) => ipcRenderer.send('steer', id, at),
  proposal: (id, choice) => ipcRenderer.send('proposal', id, choice),
  noteDen: text => ipcRenderer.send('note-den', text),
  noteDrag: (k, x, y) => ipcRenderer.send('note-drag', k, x, y),
  noteSize: h => ipcRenderer.send('note-size', h),
  puckOpen: on => ipcRenderer.send('puck-open', on),
  cardRects: r => ipcRenderer.send('card-rects', r),
  catchMouse: on => ipcRenderer.send('catch', on),
  passWheel: () => ipcRenderer.send('pass-wheel'),
  onSetup: fn => ipcRenderer.on('setup', (_e, s) => fn(s)),
  onMode: fn => ipcRenderer.on('mode', (_e, m) => fn(m)),
  onPending: fn => ipcRenderer.on('pending', (_e, n) => fn(n)),
  onLink: fn => ipcRenderer.on('link', (_e, s) => fn(s)),
  track: (id, rect) => ipcRenderer.send('track', id, rect),
  untrack: ids => ipcRenderer.send('untrack', ids),
  onShift: fn => ipcRenderer.on('shift', (_e, s) => fn(s)),
  noteAudio: buf => ipcRenderer.invoke('note-audio', buf),
});
